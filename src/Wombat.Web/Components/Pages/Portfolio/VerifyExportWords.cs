using System.Globalization;
using Wombat.Application.Features.Reporting;
using Wombat.Web.Components.Shared.Activities;

namespace Wombat.Web.Components.Pages.Portfolio;

/// <summary>
/// Verify portfolio export's words (T379, flow 13; boards R3-V01–V10, Spec 3's messages). The refusals are worded from the
/// query's typed reason (S10), never from a message's text.
/// </summary>
public static class VerifyExportWords
{
    public const string Subtitle = "Check whether a PDF was produced by Wombat, without signing in.";

    public const string FieldLabel = "Content hash (SHA-256)";

    /// <summary>The field's help (Q6), for "Enter the hash from the PDF footer"; the command list follows it.</summary>
    public const string FieldHelp =
        "The file's SHA-256: 64 hexadecimal digits, computed on your computer from the PDF you were sent. Upper or lower " +
        "case, and spaces or line breaks in it, are accepted.";

    // ─── The answer (F9, S20) ────────────────────────────────────────────────────

    /// <summary>The answer's first sentence, bold; <see cref="VerifiedRest" /> follows it.</summary>
    public const string Verified = "Export verified.";

    public const string VerifiedRest = "Wombat generated this PDF: its content is byte for byte an export Wombat recorded.";

    public const string IdsNote =
        "People are shown by their Wombat user ids, never by name. The institution that issued the portfolio can say whose " +
        "they are.";

    /// <summary>The built sentence's first half, bold, then <see cref="NotFoundRest" /> (V04).</summary>
    public const string NotFound = "No matching export found.";

    /// <summary>The built second sentence and the NEW third (V04).</summary>
    public const string NotFoundRest =
        "This hash does not correspond to any PDF generated by this system. One changed byte changes the whole hash: check " +
        "that it was computed from the file you were sent.";

    /// <summary>A check that failed (V08): today's words, "Please" dropped; its first sentence bold.</summary>
    public const string Failed = "The export could not be checked just now.";

    public const string FailedRest = "Try again in a few minutes.";

    // ─── The refusals under the field (V05, V06; S10) ───────────────────────────

    /// <summary>Only spaces (V05), the built words.</summary>
    public const string Blank = "Enter the content hash to check.";

    private const string Digits = "a SHA-256 hash has 64 hexadecimal digits (0 to 9, a to f)";

    /// <summary>The words for a refusal the query gave.</summary>
    public static string Refusal(VerifyExportAnswer answer) => answer.Refusal switch
    {
        VerifyExportRefusal.Blank => Blank,
        VerifyExportRefusal.NotHexadecimal =>
            $"This is not a SHA-256 hash: “{answer.Character}” is not a hexadecimal digit (0 to 9, a to f).",
        VerifyExportRefusal.FileNamePrefix =>
            $"This is not a SHA-256 hash: it has {answer.Length} characters, and {Digits}. The 12 in a file's name are " +
            "only its start.",
        VerifyExportRefusal.WrongLength => $"This is not a SHA-256 hash: {Characters(answer.Length)}, and {Digits}.",
        _ => throw new ArgumentOutOfRangeException(nameof(answer), answer.Refusal, "Not a refusal.")
    };

    // ─── The details list ───────────────────────────────────────────────────────

    /// <summary>"2026-10-26 22:51 SAST": a moment on the South African clock, never UTC (T325).</summary>
    public static string When(DateTime utc) => ActivityMoments.When(utc);

    /// <summary>"Once", or "3 times, the last on 2026-10-26 22:52 SAST" (V02, V07).</summary>
    public static string Exported(PortfolioExportRecordDto export) => export.Count == 1
        ? "Once"
        : $"{export.Count.ToString(CultureInfo.InvariantCulture)} times, the last on {When(export.LastExportedOn)}";

    /// <summary>"2023-01-15 to 2026-10-26", or one end; empty when the export had no filter.</summary>
    public static string Filter(DateOnly? from, DateOnly? to)
    {
        if (from.HasValue && to.HasValue) return $"{Iso(from.Value)} to {Iso(to.Value)}";
        if (from.HasValue) return $"From {Iso(from.Value)}";
        if (to.HasValue) return $"Up to {Iso(to.Value)}";
        return string.Empty;
    }

    private static string Characters(int length)
        => length == 1 ? "it has 1 character" : $"it has {length.ToString(CultureInfo.InvariantCulture)} characters";

    private static string Iso(DateOnly date) => date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
}
